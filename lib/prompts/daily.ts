// Проверка наличия мечты
export function validateGoals(request: DailyEvaluationRequest): {
  valid: boolean
  response?: DailyEvaluationResponse
} {
  // Проверка мечты
  if (!request.goals.dreamGoal || request.goals.dreamGoal === 'Не указана') {
    return { valid: false, response: NO_DREAM_RESPONSE }
  }

  // Если есть мечта - этого достаточно для оценки
  // Промежуточные цели желательны, но не обязательны
  // ИИ сможет оценить день относительно мечты даже без детальных целей
  return { valid: true }
}

