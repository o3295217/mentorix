// Построение USER промпта со всеми данными пользователя (НЕ кэшируется - всегда актуальные данные)
export function buildUserDataPrompt(request: DailyEvaluationRequest): string {
  const userProfileSection = formatUserProfile(request.userProfile)
  const contextSection = formatDailyContext(request.context)

  // Форматируем ВСЕ цели - от мечты до недели
  const yearGoals = request.goals.yearGoals.length > 0 
    ? request.goals.yearGoals.join(', ') 
    : 'Не указаны'
  const halfYearGoals = request.goals.halfYearGoals.length > 0
    ? request.goals.halfYearGoals.join(', ')
    : 'Не указаны'
  const quarterGoals = request.goals.quarterGoals.length > 0 
    ? request.goals.quarterGoals.join(', ') 
    : 'Не указаны'
  const monthGoals = request.goals.monthGoals.length > 0 
    ? request.goals.monthGoals.join(', ') 
    : 'Не указаны'
  const weekGoals = request.goals.weekGoals.length > 0 
    ? request.goals.weekGoals.join(', ') 
    : 'Не указаны'

  return `${userProfileSection}
🎯 МЕЧТА ПОЛЬЗОВАТЕЛЯ (5 лет):
${request.goals.dreamGoal}

📊 ИЕРАРХИЯ ЦЕЛЕЙ:
Год: ${yearGoals}
Полугодие: ${halfYearGoals}
Квартал: ${quarterGoals}
Месяц: ${monthGoals}
Неделя: ${weekGoals}

---

📝 СЕГОДНЯ (${request.date}):
План:
${request.planText}

✅ ФАКТ ВЫПОЛНЕНИЯ:
${request.factText}

❌ НЕ ВЫПОЛНЕНО ИЗ ПЛАНА:
${request.uncompletedTasks && request.uncompletedTasks.length > 0 ? request.uncompletedTasks.map((t, i) => `${i + 1}. ${t}`).join('\n') : 'Все задачи выполнены'}

➕ СДЕЛАНО ВНЕ ПЛАНА (перевыполнение):
${request.extraTasks && request.extraTasks.length > 0 ? request.extraTasks.map((t, i) => `${i + 1}. ${t}`).join('\n') : 'Нет'}

❌ НЕЗАКРЫТЫЕ ЗАДАЧИ ИЗ ПРОШЛОГО:
${request.openTasks.length > 0 ? request.openTasks.map((t, i) => `${i + 1}. ${t}`).join('\n') : 'Нет'}

${contextSection}

Теперь выполни оценку этого дня согласно инструкциям выше.`
}
